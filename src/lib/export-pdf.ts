import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";

const PRINT_CSS = `
  @page { margin: 18mm 16mm; }
  * { box-sizing: border-box; }
  body { font-family: "Segoe UI", Helvetica, Arial, sans-serif; color: #111; font-size: 11.5pt; line-height: 1.55; }
  header { border-bottom: 2px solid #1d7fd6; padding-bottom: 8px; margin-bottom: 18px; }
  header h1 { font-size: 16pt; margin: 0; color: #1d7fd6; }
  header p { margin: 2px 0 0; font-size: 9.5pt; color: #555; }
  h1, h2, h3, h4 { line-height: 1.25; margin: 1.1em 0 0.4em; break-after: avoid; }
  h1 { font-size: 17pt; } h2 { font-size: 14pt; } h3 { font-size: 12.5pt; }
  p, ul, ol, blockquote, pre, table { margin: 0 0 0.8em; }
  ul, ol { padding-left: 1.4em; }
  li { margin: 0.15em 0; }
  li, p, tr, pre, blockquote { break-inside: avoid; }
  code { font-family: Consolas, monospace; background: #f1f3f5; padding: 1px 4px; border-radius: 3px; font-size: 10.5pt; }
  pre { background: #f1f3f5; padding: 10px; border-radius: 6px; white-space: pre-wrap; }
  pre code { background: none; padding: 0; }
  blockquote { border-left: 3px solid #bbb; padding-left: 12px; color: #444; }
  table { border-collapse: collapse; width: 100%; }
  th, td { border: 1px solid #bbb; padding: 5px 8px; text-align: left; vertical-align: top; }
  th { background: #eef3f8; }
  hr { border: none; border-top: 1px solid #ccc; margin: 1.2em 0; }
  footer { margin-top: 24px; padding-top: 8px; border-top: 1px solid #ddd; font-size: 9pt; color: #666; }
`;

function escapeHtml(text: string): string {
  return text.replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);
}

/**
 * Opens the browser's print dialog for a clean, text-selectable rendering of
 * a Lumin reply -- "Save as PDF" there produces the file. Done in a hidden
 * iframe so the app's own page and styles stay untouched.
 */
export function exportMarkdownAsPdf(markdown: string, title = "Lumin AI"): void {
  const body = renderToStaticMarkup(
    createElement(ReactMarkdown, { remarkPlugins: [remarkGfm] }, markdown),
  );
  const safeTitle = escapeHtml(title.slice(0, 80) || "Lumin AI");
  const date = new Date().toLocaleDateString(undefined, {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${safeTitle}</title><style>${PRINT_CSS}</style></head><body>
    <header><h1>Lumin AI</h1><p>by ClearPath &middot; ${escapeHtml(date)}</p></header>
    ${body}
    <footer>Generated by Lumin AI. AI can make mistakes: verify before relying on this.</footer>
  </body></html>`;

  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  Object.assign(frame.style, {
    position: "fixed",
    right: "0",
    bottom: "0",
    width: "0",
    height: "0",
    border: "0",
  });
  document.body.appendChild(frame);
  const doc = frame.contentDocument;
  const win = frame.contentWindow;
  if (!doc || !win) {
    frame.remove();
    throw new Error("Could not prepare the PDF.");
  }
  doc.open();
  doc.write(html);
  doc.close();
  const cleanup = () => setTimeout(() => frame.remove(), 1000);
  win.addEventListener("afterprint", cleanup);
  // Give layout a tick before printing.
  setTimeout(() => {
    win.focus();
    win.print();
    // Fallback in case afterprint never fires.
    setTimeout(cleanup, 60_000);
  }, 150);
}
